import { useState } from "react";
import { Link } from "react-router-dom";
import { createSchedule } from "../services/planningApi";

function getToday() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");

  return `${year}-${month}-${day}`;
}

function slugify(name) {
  return (
    name
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "") || "project"
  );
}

function formatDate(isoDate) {
  if (!isoDate) return "—";

  return new Date(`${isoDate}T00:00:00`).toLocaleDateString(
    undefined,
    {
      month: "short",
      day: "numeric",
      year: "numeric",
    }
  );
}

function ConfidenceBanner({ responsibleAi }) {
  if (!responsibleAi) return null;

  const confidence = Number(responsibleAi.confidence || 0);
  const pct = Math.round(confidence * 100);

  const tier = responsibleAi.ai_generated
    ? "llm"
    : confidence <= 0.4
    ? "fallback"
    : "provided";

  const heading = {
    llm: "Generated by the planning model",
    fallback: "Generic placeholder plan",
    provided: "Based on the tasks you supplied",
  }[tier];

  return (
    <div className={`confidence-banner tier-${tier}`}>
      <div className="confidence-banner-top">
        <span className="confidence-banner-heading">
          {heading}
        </span>

        <span className="confidence-pct">
          {pct}% confidence
        </span>
      </div>

      <p>
        {responsibleAi.explanation ||
          "The schedule was generated by the planning system."}
      </p>
    </div>
  );
}

function Planning() {
  const [form, setForm] = useState({
    project_id: "",
    project_name: "",
    objective: "",
    start_date: getToday(),
    deadline: "",
    use_llm: true,
  });

  const [projectIdTouched, setProjectIdTouched] =
    useState(false);

  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState(null);
  const [error, setError] = useState("");

  function handleChange(event) {
    const { name, value } = event.target;

    setForm((previous) => {
      const next = {
        ...previous,
        [name]: value,
      };

      if (
        name === "project_name" &&
        !projectIdTouched
      ) {
        next.project_id = slugify(value);
      }

      return next;
    });
  }

  function handleProjectIdChange(event) {
    setProjectIdTouched(true);

    setForm((previous) => ({
      ...previous,
      project_id: event.target.value,
    }));
  }

  const deadlineBeforeStart =
    form.start_date &&
    form.deadline &&
    form.deadline < form.start_date;

  async function handleSubmit(event) {
    event.preventDefault();

    setError("");
    setResult(null);

    if (deadlineBeforeStart) {
      setError(
        "The deadline can't be before the start date."
      );
      return;
    }

    if (!form.project_id.trim()) {
      setError("Please enter a project ID.");
      return;
    }

    if (!form.project_name.trim()) {
      setError("Please enter a project name.");
      return;
    }

    if (!form.objective.trim()) {
      setError("Please describe the project objective.");
      return;
    }

    setLoading(true);

    try {
      const schedule = await createSchedule(form);
      setResult(schedule);
    } catch (err) {
      setError(
        err?.message ||
          "Unable to generate the project schedule."
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="page planning-page">

      <div className="page-header">
        <span className="badge">
          AI PLANNING
        </span>

        <h2>
          Create a project schedule
        </h2>

        <p>
          Describe what the project needs to achieve.
          The Planning Agent breaks it into tasks,
          works out dependencies and risk buffers,
          and lays out dates against your deadline.
        </p>
      </div>

      <div className="planning-layout">

        {/* ==================================================
            FORM
            ================================================== */}

        <form
          className="planning-form-card"
          onSubmit={handleSubmit}
        >

          <div className="form-row">

            <div className="form-field">
              <label htmlFor="project_name">
                Project name
              </label>

              <input
                id="project_name"
                name="project_name"
                value={form.project_name}
                onChange={handleChange}
                placeholder="Website redesign"
                required
              />
            </div>

            <div className="form-field">

              <label htmlFor="project_id">
                Project ID
                <span className="field-hint">
                  used to look it up later
                </span>
              </label>

              <input
                id="project_id"
                name="project_id"
                value={form.project_id}
                onChange={handleProjectIdChange}
                placeholder="website-redesign"
                required
              />

            </div>

          </div>

          <div className="form-field">

            <label htmlFor="objective">
              What does this project need to achieve?
            </label>

            <textarea
              id="objective"
              name="objective"
              value={form.objective}
              onChange={handleChange}
              placeholder="e.g. Rebuild the storefront with a faster checkout flow and live inventory sync across three warehouses."
              rows={6}
              minLength={10}
              required
            />

            <span className="field-hint">
              The more specific this is, the more useful
              the generated tasks will be.
            </span>

          </div>

          <div className="form-row">

            <div className="form-field">

              <label htmlFor="start_date">
                Start date
              </label>

              <input
                id="start_date"
                name="start_date"
                type="date"
                value={form.start_date}
                onChange={handleChange}
                required
              />

            </div>

            <div className="form-field">

              <label htmlFor="deadline">
                Deadline
              </label>

              <input
                id="deadline"
                name="deadline"
                type="date"
                value={form.deadline}
                min={form.start_date}
                onChange={handleChange}
                required
              />

            </div>

          </div>

          {deadlineBeforeStart && (
            <p className="field-error">
              The deadline can't be before the start date.
            </p>
          )}

          <label className="toggle-row">

            <input
              type="checkbox"
              checked={form.use_llm}
              onChange={(event) =>
                setForm((previous) => ({
                  ...previous,
                  use_llm: event.target.checked,
                }))
              }
            />

            <span>
              <strong>
                Generate tasks with the planning model
              </strong>

              <small>
                Off uses a generic placeholder task list
                instead — useful for testing dates and
                dependencies without calling the model.
              </small>
            </span>

          </label>

          <button
            className="primary-button"
            type="submit"
            disabled={loading}
          >
            {loading
              ? "Building schedule…"
              : "Generate schedule"}
          </button>

          {error && (
            <div className="error-message">
              {error}
            </div>
          )}

        </form>

        {/* ==================================================
            SIDE PANEL
            ================================================== */}

        <aside className="planning-side-panel">

          {!result && !loading && (
            <div className="side-panel-intro">

              <h3>
                What you'll get
              </h3>

              <ul className="intro-steps">

                <li>
                  A task breakdown with realistic
                  durations and dependencies
                </li>

                <li>
                  Dates laid out against your start
                  date and deadline
                </li>

                <li>
                  The critical path and high-risk
                  tasks flagged
                </li>

                <li>
                  A clear label showing whether the plan
                  came from the model or a placeholder
                </li>

              </ul>

            </div>
          )}

          {loading && (
            <div className="side-panel-loading">

              <div
                className="spinner"
                aria-hidden="true"
              />

              <p>
                Working out tasks, dependencies
                and dates…
              </p>

            </div>
          )}

          {result && (
            <div className="side-panel-result">

              <ConfidenceBanner
                responsibleAi={result.responsible_ai}
              />

              <div className="result-stats">

                <div>
                  <span>
                    Duration
                  </span>

                  <strong>
                    {result.analysis?.total_duration_days ?? "—"} days
                  </strong>
                </div>

                <div>
                  <span>
                    Deadline
                  </span>

                  <strong
                    className={
                      result.analysis?.deadline_met
                        ? "ok"
                        : "warn"
                    }
                  >
                    {result.analysis?.deadline_met
                      ? "On track"
                      : `+${result.analysis?.delay_days || 0}d over`}
                  </strong>
                </div>

                <div>
                  <span>
                    Tasks
                  </span>

                  <strong>
                    {result.schedule?.length || 0}
                  </strong>
                </div>

              </div>

              <ol className="result-task-list">

                {(result.schedule || []).map((task) => (
                  <li
                    key={task.task_id}
                    className={
                      task.is_critical
                        ? "is-critical"
                        : ""
                    }
                  >

                    <span className="task-id">
                      {task.task_id}
                    </span>

                    <span className="task-name">
                      {task.name}
                    </span>

                    <span className="task-dates">
                      {formatDate(task.planned_start)}
                      {" – "}
                      {formatDate(task.planned_end)}
                    </span>

                  </li>
                ))}

              </ol>

              <Link
                to={`/schedule/${encodeURIComponent(
                  result.project_id
                )}`}
                className="primary-button view-schedule-link"
              >
                View full schedule →
              </Link>

            </div>
          )}

        </aside>

      </div>

    </div>
  );
}

export default Planning;