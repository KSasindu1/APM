function Schedule({ session, onUnauthorized }) {

  const {
    projectId: routeProjectId,
  } = useParams();

  const navigate = useNavigate();
  const { key: routeKey } = useLocation();
  const currentProjectId = routeProjectId
    ? decodeURIComponent(routeProjectId).trim()
    : "";


  /*
   * This is now the value used by the
   * SINGLE search bar inside ProjectTable.
   */
  const [projectId, setProjectId] =
    useState(
      routeProjectId
        ? decodeURIComponent(
            routeProjectId
          )
        : ""
    );


  const [projectList, setProjects] =
    useState(null);

  const [storedSchedule, setSchedule] =
    useState(null);

  const projects = projectList && projectList.session === session
    ? projectList.projects
    : [];
  const schedule = storedSchedule && storedSchedule.session === session &&
    storedSchedule.result.project_id === currentProjectId
    ? storedSchedule.result
    : null;

  const [loading, setLoading] =
    useState(false);

  const [projectsLoading, setProjectsLoading] =
    useState(true);

  const [message, setMessage] =
    useState("");

  const [error, setError] =
    useState("");

  const [expandedTask, setExpandedTask] =
    useState(null);


  const scope = useRef({ mounted: false, generation: 0, requests: new Map() });

  const cancelRequest = useCallback((kind) => {
    scope.current.requests.get(kind)?.controller.abort();
    scope.current.requests.delete(kind);
  }, []);

  const invalidateRequests = useCallback(() => {
    const current = scope.current;
    current.generation += 1;
    current.requests.forEach(operation => operation.controller.abort());
    current.requests.clear();
  }, []);

  // Invalidate at commit, before a late response can affect another route/account.
  useLayoutEffect(() => {
    const current = scope.current;
    current.mounted = true;
    current.session = session;
    current.projectId = currentProjectId;
    current.routeKey = routeKey;
    return () => {
      current.mounted = false;
      invalidateRequests();
    };
  }, [session, currentProjectId, routeKey, invalidateRequests]);

  const beginRequest = useCallback((kind) => {
    const current = scope.current;
    if (!current.mounted || current.session !== session ||
      current.projectId !== currentProjectId || current.routeKey !== routeKey) return null;
    cancelRequest(kind);
    const operation = { kind, generation: current.generation, controller: new AbortController() };
    current.requests.set(kind, operation);
    return operation;
  }, [session, currentProjectId, routeKey, cancelRequest]);

  const isCurrent = useCallback((operation) => {
    const current = scope.current;
    return current.mounted && current.generation === operation.generation &&
      current.session === session && current.projectId === currentProjectId &&
      current.routeKey === routeKey && current.requests.get(operation.kind) === operation &&
      !operation.controller.signal.aborted;
  }, [session, currentProjectId, routeKey]);

  const finishRequest = useCallback((operation, setBusy) => {
    if (!isCurrent(operation)) return;
    scope.current.requests.delete(operation.kind);
    setBusy(false);
  }, [isCurrent]);

  const loadProjects = useCallback(async () => {

    const operation = beginRequest("list");
    if (!operation) return;
    setProjectsLoading(true);

    try {

      const result =
        await getAllSchedules({ session, signal: operation.controller.signal });

      if (!isCurrent(operation)) return;
      setProjects({ session, projects: Array.isArray(result) ? result : [] });

    } catch (err) {

      if (!isCurrent(operation) || err?.name === "AbortError") return;
      if (err.status === 401) onUnauthorized?.(session);
      setError(planningErrorMessage(err));

    } finally {

      finishRequest(operation, setProjectsLoading);

    }
  }, [beginRequest, isCurrent, finishRequest, session, onUnauthorized]);


  function loadSchedule(id) {

    const cleanId =
      String(id || "").trim();

    if (!cleanId) {

      setError(
        "Enter a project ID to look up its schedule."
      );

      return;
    }

    invalidateRequests();
    setSchedule(null);
    setLoading(false);
    setProjectsLoading(false);
    setError("");
    setMessage("");
    setProjectId(cleanId);
    setExpandedTask(null);

    navigate(
      `/schedule/${encodeURIComponent(cleanId)}`,
      { replace: true }
    );
  }


  const loadScheduleWithoutNavigation = useCallback(async (id) => {

    const cleanId = String(id || "").trim();
    if (!cleanId) return;
    const operation = beginRequest("detail");
    if (!operation) return;

    setLoading(true);
    setError("");
    setMessage("");

    try {

      const result =
        await getSchedule(cleanId, { session, signal: operation.controller.signal });

      if (!isCurrent(operation)) return;
      setSchedule({ session, result });
      setExpandedTask(null);

    } catch (err) {

      if (!isCurrent(operation) || err?.name === "AbortError") return;
      setSchedule(null);
      if (err.status === 401) onUnauthorized?.(session);
      setError(planningErrorMessage(err));

    } finally {

      finishRequest(operation, setLoading);

    }
  }, [beginRequest, isCurrent, finishRequest, session, onUnauthorized]);


  useEffect(() => {

    loadProjects();

  }, [loadProjects]);


  useEffect(() => {

    setSchedule(null);
    setLoading(false);

    if (!routeProjectId) return;

    const decodedId = decodeURIComponent(routeProjectId);
    setProjectId(decodedId);
    loadScheduleWithoutNavigation(decodedId);

  }, [routeProjectId, routeKey, loadScheduleWithoutNavigation]);


  /*
   * Look up handler used by the button
   * inside ProjectTable.
   */
  function handleLookup() {

    const cleanId =
      projectId.trim();

    if (!cleanId) {

      setError(
        "Enter a project ID."
      );

      return;
    }

    loadSchedule(cleanId);
  }


  function handleBackToProjects() {

    invalidateRequests();
    setLoading(false);
    setProjectsLoading(false);
    setSchedule(null);

    setError("");

    setMessage("");

    setProjectId("");

    setExpandedTask(null);

    navigate("/schedule");

  }


  async function handleDelete() {

    if (!schedule) {
      return;
    }

    const confirmed =
      window.confirm(
        `Delete the schedule for "${schedule.project_name}"? This can't be undone.`
      );

    if (!confirmed) {
      return;
    }

    cancelRequest("detail");
    const operation = beginRequest("mutation");
    if (!operation) return;
    setLoading(true);
    setError("");
    setMessage("");

    try {

      await deleteSchedule(
        schedule.project_id,
        { session, signal: operation.controller.signal }
      );

      if (!isCurrent(operation)) return;
      setSchedule(null);

      setMessage(
        "Schedule deleted successfully."
      );

      await loadProjects();

      if (!isCurrent(operation)) return;
      navigate("/schedule");

    } catch (err) {

      if (!isCurrent(operation) || err?.name === "AbortError") return;
      if (err.status === 401) onUnauthorized?.(session);
      setError(planningErrorMessage(err));

    } finally {

      finishRequest(operation, setLoading);

    }
  }


  async function handleRegenerate() {

    if (!schedule) {
      return;
    }

    const tasks =
      Array.isArray(
        schedule.schedule
      )
        ? schedule.schedule
        : [];

    if (tasks.length === 0) {

      setError(
        "There are no tasks to recalculate."
      );

      return;
    }

    cancelRequest("detail");
    const operation = beginRequest("mutation");
    if (!operation) return;
    setLoading(true);
    setError("");
    setMessage("");

    try {

      const updated =
        await updateSchedule(
          schedule.project_id,
          {
            project_id:
              schedule.project_id,

            project_name:
              schedule.project_name,

            objective:
              tasks
                .map(
                  (task) =>
                    task.name
                )
                .join("; ") ||
              "Re-scheduled project",

            start_date:
              tasks[0]
                ?.planned_start,

            deadline:
              tasks[
                tasks.length - 1
              ]?.planned_end,

            tasks:
              tasks.map(
                (task) => ({
                  task_id:
                    task.task_id,

                  name:
                    task.name,

                  description:
                    task.description ||
                    "",

                  duration_days:
                    task.duration_days,

                  priority:
                    task.priority,

                  dependencies:
                    task.dependencies ||
                    [],

                  resource_id:
                    task.resource_id,
                })
              ),

            resources: [],
            risks: [],
            use_llm: false,
          },
          { session, signal: operation.controller.signal }
        );

      if (!isCurrent(operation)) return;
      setSchedule({ session, result: updated });

      setMessage(
        "Schedule recalculated from its current tasks."
      );

      await loadProjects();

    } catch (err) {

      if (!isCurrent(operation) || err?.name === "AbortError") return;
      // A failed/ambiguous update cannot establish that the stored plan is current.
      setSchedule(null);
      if (err.status === 401) onUnauthorized?.(session);
      setError(planningErrorMessage(err));

    } finally {

      finishRequest(operation, setLoading);

    }
  }


  return (
    <div className="page schedule-page">

      <div className="page-header">

        <span className="badge">
          SCHEDULE
        </span>

        <h2>
          Project schedules
        </h2>

        <p>
          Search your saved projects, view
          schedules, timelines, deadlines and
          task details.
        </p>

      </div>


      {/* ==================================================
          ERROR
          ================================================== */}

      {error && (
        <div className="error-message">
          {error}
        </div>
      )}


      {/* ==================================================
          SUCCESS MESSAGE
          ================================================== */}

      {message && (
        <div className="success-message">
          {message}
        </div>
      )}


      {/* ==================================================
          PROJECT LIST

          IMPORTANT:
          There is NO separate search bar here.

          ProjectTable contains the only search bar
          and Look up button.
          ================================================== */}

      {!schedule && (
        <ProjectTable
          projects={projects}
          searchValue={projectId}
          onSearchChange={setProjectId}
          onView={loadSchedule}
          onLookup={handleLookup}
          loading={
            projectsLoading ||
            loading
          }
        />
      )}


      {/* ==================================================
          CURRENT SCHEDULE
          ================================================== */}

      {schedule && (
        <div className="schedule-view">

          {/* BACK TO PROJECTS */}

          <button
            type="button"
            className="secondary-button schedule-back-button"
            onClick={
              handleBackToProjects
            }
          >
            ← Back to all projects
          </button>


          {/* HEADER */}

          <div className="schedule-view-header">

            <div>

              <span className="project-label">
                PROJECT
              </span>

              <h3>
                {schedule.project_name}
              </h3>

              <p className="task-id">
                {schedule.project_id}
              </p>

            </div>


            <div className="schedule-actions">

              <Link
                to={`/monitoring/${encodeURIComponent(schedule.project_id)}`}
                className="secondary-button"
              >
                Monitor progress
              </Link>

              <button
                type="button"
                className="secondary-button"
                onClick={
                  handleRegenerate
                }
                disabled={loading}
              >
                Recalculate dates
              </button>

              <button
                type="button"
                className="danger-button"
                onClick={
                  handleDelete
                }
                disabled={loading}
              >
                Delete
              </button>

            </div>

          </div>


          {/* STATS */}

          <div className="schedule-stats">

            <div>

              <span>
                Start
              </span>

              <strong>
                {formatDate(
                  getProjectStart(
                    schedule
                  )
                )}
              </strong>

            </div>


            <div>

              <span>
                Planned End
              </span>

              <strong>
                {formatDate(
                  getProjectPlannedEnd(
                    schedule
                  )
                )}
              </strong>

            </div>


            <div>

              <span>
                Duration
              </span>

              <strong>
                {schedule.analysis
                  ?.total_duration_days ??
                  "—"}{" "}
                days
              </strong>

            </div>


            <div>

              <span>
                Tasks
              </span>

              <strong>
                {schedule.schedule
                  ?.length || 0}
              </strong>

            </div>


            <div>

              <span>
                Critical path
              </span>

              <strong>
                {schedule.analysis
                  ?.critical_path
                  ?.length || 0}{" "}
                tasks
              </strong>

            </div>

          </div>


          {/* RESPONSIBLE AI */}

          <ConfidenceBanner
            responsibleAi={
              schedule.responsible_ai
            }
            warnings={
              schedule.warnings || []
            }
          />


          {/* TIMELINE */}

          <Timeline
            schedule={
              schedule.schedule || []
            }
          />


          {/* TASK DETAILS */}

          <div className="task-detail-list">

            <h4>
              Task details
            </h4>

            {(schedule.schedule || [])
              .map((task) => (

                <div
                  key={
                    task.task_id
                  }
                  className={`task-detail-row ${
                    task.is_critical
                      ? "is-critical"
                      : ""
                  }`}
                  onClick={() =>
                    setExpandedTask(
                      expandedTask ===
                        task.task_id
                        ? null
                        : task.task_id
                    )
                  }
                >

                  <div className="task-detail-summary">

                    <span className="task-id">
                      {task.task_id}
                    </span>

                    <span className="task-detail-name">
                      {task.name}
                    </span>

                    <RiskDot
                      level={
                        task.risk_level
                      }
                    />

                    <span className="task-detail-dates">
                      {formatDate(
                        task.planned_start
                      )}
                      {" – "}
                      {formatDate(
                        task.planned_end
                      )}
                    </span>

                    <span
                      className={`priority-chip priority-${String(
                        task.priority ||
                          "medium"
                      ).toLowerCase()}`}
                    >
                      {task.priority ||
                        "MEDIUM"}
                    </span>

                  </div>


                  {expandedTask ===
                    task.task_id && (

                    <div className="task-detail-expanded">

                      {task.description && (
                        <p>
                          {
                            task.description
                          }
                        </p>
                      )}

                      {task.rationale && (
                        <p className="task-rationale">
                          {
                            task.rationale
                          }
                        </p>
                      )}

                      {Array.isArray(
                        task.dependencies
                      ) &&
                        task
                          .dependencies
                          .length >
                          0 && (

                          <p className="task-deps">
                            Depends on:{" "}
                            {task.dependencies.join(
                              ", "
                            )}
                          </p>

                        )}

                    </div>

                  )}

                </div>

              ))}

          </div>

        </div>
      )}

    </div>
  );
}


export default Schedule;