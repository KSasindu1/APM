create table if not exists public.project_schedules (
    id bigint generated by default as identity primary key,

    project_id text not null unique,

    project_name text not null,

    schedule jsonb not null,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now()
);


create index if not exists idx_project_schedules_project_id
on public.project_schedules(project_id);


create index if not exists idx_project_schedules_created_at
on public.project_schedules(created_at desc);


create or replace function public.update_project_schedules_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;


drop trigger if exists trg_project_schedules_updated_at
on public.project_schedules;


create trigger trg_project_schedules_updated_at
before update on public.project_schedules
for each row
execute function public.update_project_schedules_updated_at();


alter table public.project_schedules enable row level security;