from __future__ import annotations

from app.agents.planning.agent import PlanningAgent
from app.agents.planning.tools import (
    calculate_critical_path,
    detect_dependency_cycle,
    schedule_tasks,
    validate_dependencies,
    validate_unique_task_ids,
)
from app.model.planning import (
    ProjectPlanningRequest,
    ResponsibleAIInfo,
    ScheduleAnalysis,
    ScheduleResponse,
    ScheduledTask,
)


CONFIDENCE_BY_SOURCE = {
    "user_provided": 0.95,
    "llm": 0.85,
    "fallback": 0.35,
}


EXPLANATION_BY_SOURCE = {
    "user_provided": (
        "Tasks were supplied directly by the caller. "
        "The schedule, dates, critical path, and risk "
        "buffers were computed algorithmically."
    ),
    "llm": (
        "Tasks were generated by the LLM from the project "
        "objective, then validated and scheduled using "
        "deterministic dependency, duration, and risk rules."
    ),
    "fallback": (
        "The LLM was unavailable, failed, or was disabled. "
        "A deterministic task template was used instead. "
        "The fallback plan should be reviewed by a human."
    ),
}


class PlanningService:

    def __init__(
        self,
        agent: PlanningAgent | None = None,
    ) -> None:

        self.agent = (
            agent
            or PlanningAgent()
        )

    def create_schedule(
        self,
        request: ProjectPlanningRequest,
    ) -> ScheduleResponse:

        warnings: list[str] = []

        if request.deadline < request.start_date:
            raise ValueError(
                "Project deadline cannot be before project start date."
            )

        # --------------------------------------------
        # 1. Determine task source
        # --------------------------------------------

        if request.tasks:

            tasks = request.tasks
            task_source = "user_provided"

        elif request.use_llm:

            tasks = self.agent.generate_tasks(
                project_name=request.project_name,
                objective=request.objective,
                start_date=request.start_date,
                deadline=request.deadline,
            )

            if self.agent.last_generation_was_llm:

                task_source = "llm"

            else:

                task_source = "fallback"

                warnings.append(
                    "LLM task generation was unavailable "
                    "or invalid. Deterministic fallback "
                    "tasks were used."
                )

        else:

            tasks = self.agent.fallback_tasks(
                objective=request.objective
            )

            task_source = "fallback"

            warnings.append(
                "LLM generation was disabled. "
                "Deterministic fallback tasks were used."
            )

        # --------------------------------------------
        # 2. Validate tasks
        # --------------------------------------------

        if not tasks:
            raise ValueError(
                "No tasks available for scheduling."
            )

        duplicate_errors = (
            validate_unique_task_ids(tasks)
        )

        if duplicate_errors:
            raise ValueError(
                "; ".join(duplicate_errors)
            )

        dependency_errors = (
            validate_dependencies(tasks)
        )

        if dependency_errors:
            raise ValueError(
                "; ".join(dependency_errors)
            )

        if detect_dependency_cycle(tasks):
            raise ValueError(
                "Circular dependency detected."
            )

        # --------------------------------------------
        # 3. Validate resources
        # --------------------------------------------

        resource_ids = {
            resource.resource_id
            for resource in request.resources
            if resource.resource_id
        }

        for task in tasks:

            if (
                task.resource_id
                and task.resource_id not in resource_ids
            ):
                warnings.append(
                    f"Task {task.task_id} references unknown "
                    f"resource '{task.resource_id}'."
                )

        # --------------------------------------------
        # 4. Generate schedule
        # --------------------------------------------

        raw_schedule = schedule_tasks(
            tasks=tasks,
            start_date=request.start_date,
            risks=request.risks,
        )

        if not raw_schedule:
            raise ValueError(
                "Unable to generate a schedule."
            )

        # --------------------------------------------
        # 5. Critical path
        # --------------------------------------------

        critical_path, critical_duration = (
            calculate_critical_path(
                raw_schedule
            )
        )

        critical_set = set(
            critical_path
        )

        # --------------------------------------------
        # 6. Convert to response
        # --------------------------------------------

        scheduled_tasks: list[
            ScheduledTask
        ] = []

        for item in raw_schedule:

            task = item["task"]

            is_critical = (
                task.task_id in critical_set
            )

            rationale = self.build_rationale(
                task=task,
                is_critical=is_critical,
                risk_level=item["risk_level"],
                risk_buffer=item["risk_buffer"],
            )

            scheduled_tasks.append(
                ScheduledTask(
                    task_id=task.task_id,
                    name=task.name,
                    description=task.description,
                    duration_days=item["duration"],
                    priority=task.priority,
                    dependencies=task.dependencies,
                    planned_start=item["start_date"],
                    planned_end=item["end_date"],
                    resource_id=task.resource_id,
                    is_critical=is_critical,
                    risk_level=item["risk_level"],
                    risk_buffer_days=item["risk_buffer"],
                    rationale=rationale,
                )
            )

        # --------------------------------------------
        # 7. Project duration
        # --------------------------------------------

        project_end = max(
            task.planned_end
            for task in scheduled_tasks
        )

        total_duration = (
            project_end
            - request.start_date
        ).days + 1

        available_duration = (
            request.deadline
            - request.start_date
        ).days + 1

        deadline_met = (
            project_end <= request.deadline
        )

        delay_days = max(
            0,
            (
                project_end
                - request.deadline
            ).days,
        )

        if not deadline_met:

            warnings.append(
                "The generated schedule exceeds the "
                f"project deadline by {delay_days} day(s)."
            )

        # --------------------------------------------
        # 8. Risk warnings
        # --------------------------------------------

        high_risk_tasks = [
            task
            for task in scheduled_tasks
            if task.risk_level.value
            in {"HIGH", "CRITICAL"}
        ]

        if high_risk_tasks:

            warnings.append(
                f"{len(high_risk_tasks)} task(s) have "
                "high or critical risk."
            )

        # --------------------------------------------
        # 9. Utilization
        # --------------------------------------------

        utilization = (
            total_duration
            / max(
                1,
                available_duration,
            )
        ) * 100

        utilization = min(
            100.0,
            utilization,
        )

        # --------------------------------------------
        # 10. Analysis
        # --------------------------------------------

        analysis = ScheduleAnalysis(
            total_duration_days=total_duration,
            available_duration_days=available_duration,
            deadline_met=deadline_met,
            delay_days=delay_days,
            critical_path=critical_path,
            critical_path_duration_days=critical_duration,
            utilization_percentage=round(
                utilization,
                2,
            ),
            warnings=list(warnings),
        )

        # --------------------------------------------
        # 11. Responsible AI
        # --------------------------------------------

        responsible_ai = ResponsibleAIInfo(
            ai_generated=(
                task_source == "llm"
            ),
            human_review_required=True,
            confidence=CONFIDENCE_BY_SOURCE[
                task_source
            ],
            explanation=EXPLANATION_BY_SOURCE[
                task_source
            ],
            limitations=[
                "Task duration estimates may be inaccurate.",
                "LLM-generated tasks may require correction.",
                "External organizational constraints may be missing.",
                "Resource availability is not capacity-scheduled.",
                "Risk estimates depend on supplied risk information.",
                "The generated schedule is a planning recommendation.",
            ],
        )

        return ScheduleResponse(
            project_id=request.project_id,
            project_name=request.project_name,
            schedule=scheduled_tasks,
            analysis=analysis,
            responsible_ai=responsible_ai,
            warnings=warnings,
        )

    @staticmethod
    def build_rationale(
        task,
        is_critical,
        risk_level,
        risk_buffer,
    ) -> str:

        reasons: list[str] = []

        if task.dependencies:

            reasons.append(
                "Scheduled after its dependencies."
            )

        else:

            reasons.append(
                "Scheduled from the project start date."
            )

        reasons.append(
            f"Priority is {task.priority.value}."
        )

        if is_critical:

            reasons.append(
                "Task is part of the critical path."
            )

        if risk_buffer > 0:

            reasons.append(
                f"{risk_buffer} risk-buffer day(s) added."
            )

        if risk_level.value != "LOW":

            reasons.append(
                f"Risk level is {risk_level.value}."
            )

        return " ".join(reasons)